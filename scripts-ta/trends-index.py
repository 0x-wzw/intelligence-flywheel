#!/usr/bin/env python3
"""Rebuild Knowledge/00-Raw/trends/README.md — the index of all daily trend reports.

The trend corpus used to be split across two directories: the six market-trends
generators were repointed to Knowledge/00-Raw/trends/ on 2026-07-22 while
aised-eoi-rfp-crawler.py kept writing to System/Trends/. That split was closed on
2026-07-26 — the 41 legacy reports were moved across, the crawler was repointed,
and System/Trends/ was retired. One sink, one index.

Idempotent: regenerates the "Report Index" section from the files on disk and
preserves everything from "## Cron Schedule" onward verbatim, plus any Notion
URLs already recorded against a report.

Run daily after the last generator (aised-eoi-rfp-crawler, 12:00 MYT).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hermes_feeds import authorship_tag  # single source for the authorship tag

VAULT = os.path.expanduser("~/Documents/Obsidian Vault")
README = os.path.join(VAULT, "Knowledge", "00-Raw", "trends", "README.md")
SCAN_DIRS = ["Knowledge/00-Raw/trends"]

HEADER = """---
type: index
domain: knowledge
status: active
tags: [trends, intelligence, index, {author}]
---

# 📁 Market Intelligence Reports

> Daily market trend reports across 6 verticals. Generated by Hermes cron jobs at 00:00-05:00 daily. Pushed to Notion and published to [intelligence.teoh.my](https://intelligence.teoh.my).
>
> **This index is generated** by `~/.hermes/scripts/trends-index.py` (daily 12:30 MYT). Edits to the Report Index below are overwritten; edit the sections after it freely.
"""

# slug -> (sort key / publish time, vertical label, description used as link alias)
VERTICALS = {
    "csuite-leadership-trends": ("00:00", "💼 C-Suite Leadership", "CIO, CDO, CIO Investment, CTO, Digital Strategy"),
    "fnb-trends": ("01:00", "🍔 F&B & Consumer", "F&B, Fast Food, Halal, Loyalty, Delivery, Food Security"),
    "hospitality-trends": ("02:00", "🏨 Hospitality & Healthcare", "Hotel, Tourism, Co-Living, Experiential Travel, Retirement, TCM, Rehab"),
    "market-trends": ("03:00", "👕 Fashion & Retail", "Fashion, Fast Fashion, Retail, Supermarkets, E-Commerce, Sustainability"),
    "property-infra-energy-trends": ("04:00", "🏗️ Property & Infrastructure", "Property, Construction, Gen Z, ASEAN, Data Centers, Infra, Renewable Energy"),
    "ai-science-investment-trends": ("05:00", "🤖 AI & Science", "AI/ML, Post-Quantum, Fintech, Data Arch, Agentic AI, AGI, VC/PE, Science"),
    "llm-learning-scan": ("06:00", "🧠 LLM Learning", "LLM research, papers, model releases, learning resources"),
    "aised-eoi-rfp": ("12:00", "🏛️ AISED EoI/RFP", "Selangor sovereign economic development tenders, EoI and RFP notices"),
    "market-intelligence": ("—", "📊 Market Intelligence", "Cross-vertical synthesis"),
}

DATED = re.compile(r"^(?P<slug>.+?)-(?P<date>\d{4}-\d{2}-\d{2})\.md$")


def collect():
    """Return {date: [(time, label, alias, vault_path)]} for every dated report."""
    reports = {}
    for d in SCAN_DIRS:
        full = os.path.join(VAULT, d)
        if not os.path.isdir(full):
            continue
        for fname in os.listdir(full):
            m = DATED.match(fname)
            if not m:
                continue
            slug, date = m.group("slug"), m.group("date")
            time, label, alias = VERTICALS.get(slug, ("—", slug, slug))
            # link by full vault path so it resolves regardless of which dir holds it
            path = f"{d}/{fname[:-3]}"
            reports.setdefault(date, []).append((time, label, alias, path))
    return reports


def existing_notion_links(text):
    """Map report basename -> Notion markdown link, so URLs already indexed survive."""
    out = {}
    for line in text.splitlines():
        link = re.search(r"\[\[([^\]\\|]+)", line)
        notion = re.search(r"\[Notion\]\((https?://[^)]+)\)", line)
        if link and notion:
            out[os.path.basename(link.group(1))] = notion.group(1)
    return out


def preserved_tail(text):
    """Everything from '## Cron Schedule' onward is hand-authored — keep it as-is."""
    idx = text.find("## Cron Schedule")
    return text[idx:] if idx != -1 else ""


def build(reports, notion, tail):
    parts = [HEADER.format(author=authorship_tag()), "\n## Report Index\n"]
    for date in sorted(reports, reverse=True):
        rows = sorted(reports[date], key=lambda r: (r[0], r[1]))
        has_notion = any(notion.get(os.path.basename(p)) for _, _, _, p in rows)
        parts.append(f"\n### {date}\n")
        if has_notion:
            parts.append("| Time | Vertical | Report | Notion |")
            parts.append("|------|----------|--------|--------|")
        else:
            parts.append("| Time | Vertical | Report |")
            parts.append("|------|----------|--------|")
        for time, label, alias, path in rows:
            # escape the pipe: this wikilink sits inside a markdown table cell
            cell = f"[[{path}\\|{alias}]]"
            if has_notion:
                url = notion.get(os.path.basename(path))
                n = f"[Notion]({url})" if url else "—"
                parts.append(f"| {time} | {label} | {cell} | {n} |")
            else:
                parts.append(f"| {time} | {label} | {cell} |")
        parts.append("")
    if tail:
        parts.append(tail.rstrip() + "\n")
    return "\n".join(parts)


def main():
    text = open(README, encoding="utf-8").read() if os.path.exists(README) else ""
    reports = collect()
    if not reports:
        print("trends-index: no dated reports found — leaving README untouched")
        return 1
    new = build(reports, existing_notion_links(text), preserved_tail(text))
    if new == text:
        print(f"trends-index: up to date ({sum(len(v) for v in reports.values())} reports)")
        return 0
    # Use subprocess to write (macOS cron sandbox workaround)
    import subprocess, tempfile
    tmp = tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', delete=False, suffix='.md')
    tmp.write(new)
    tmp.close()
    subprocess.run(["cp", tmp.name, README], check=True)
    os.unlink(tmp.name)
    print(f"trends-index: rebuilt {README} — "
          f"{sum(len(v) for v in reports.values())} reports across {len(reports)} dates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
